/**
 * element-collections.mjs — the element-keyed collections the browser half keeps,
 * by file (C1). A collection keyed by a page node is only safe while its author
 * knows how long it is held: the entries have to leave when the node's level
 * ends (docs/ARCHITECTURE.md 的持有期限一节). This record makes every one of
 * them visible, and every new one a decision: the check fails when a file keeps
 * more than the record says, and when the record carries a count a file no
 * longer has.
 *
 * Run through `npm run element-collections` to write the record.
 */
import fs from 'node:fs'
import path from 'node:path'

const ROOT = path.resolve(import.meta.dirname, '..', '..')
const RECORD = path.join(import.meta.dirname, 'data', 'element-collections.json')
/** A map or set whose keys are page nodes: the shape whose lifetime has to be answered. */
const PATTERN = /new\s+(?:Map|Set)<\s*(?:Element|HTMLElement)\b/g
const DIRS = ['packages/client/src', 'packages/engine/src']

/** Every TypeScript source in the two halves, and how many element-keyed collections it keeps. */
function counted() {
  const files = {}
  const walk = (dir) => {
    for (const entry of fs.readdirSync(path.join(ROOT, dir), { withFileTypes: true })) {
      const next = `${dir}/${entry.name}`
      if (entry.isDirectory()) walk(next)
      else if (entry.name.endsWith('.ts')) {
        const text = fs.readFileSync(path.join(ROOT, next), 'utf8')
        const found = [...text.matchAll(PATTERN)].length
        if (found > 0) files[next] = found
      }
    }
  }
  for (const dir of DIRS) walk(dir)
  return files
}

/** What the tree keeps against what the record says: one line per disagreement. */
export function checkElementCollections() {
  const tree = counted()
  let recorded = {}
  try {
    recorded = JSON.parse(fs.readFileSync(RECORD, 'utf8')).files
  } catch (error) {
    return { total: 0, files: 0, problems: [`packages/testing/data/element-collections.json is unreadable (${error.message})`] }
  }
  const problems = []
  for (const [file, count] of Object.entries(tree)) {
    const had = recorded[file]
    if (had === undefined) problems.push(`${file}: keeps ${count} element-keyed collection(s), recorded nowhere — run \`npm run element-collections\`, and say which lifetime level each belongs to`)
    else if (count > had) problems.push(`${file}: keeps ${count} element-keyed collections, the record says ${had} — a new one writes its lifetime level beside it (docs/ARCHITECTURE.md), then \`npm run element-collections\``)
    else if (count < had) problems.push(`${file}: keeps ${count} element-keyed collections, the record says ${had} — run \`npm run element-collections\``)
  }
  for (const file of Object.keys(recorded)) {
    if (tree[file] === undefined) problems.push(`${file}: the record carries ${recorded[file]} element-keyed collection(s) this file no longer keeps`)
  }
  return { total: Object.values(tree).reduce((sum, count) => sum + count, 0), files: Object.keys(tree).length, problems }
}

/** Write the record from the tree as it stands. */
export function writeElementCollections() {
  const tree = counted()
  fs.writeFileSync(RECORD, `${JSON.stringify({
    about: 'The element-keyed collections the browser half keeps, by file (C1). A count only shrinks: a new collection is a decision about how long its entries are held, written in the comment beside it as one of the four levels in docs/ARCHITECTURE.md. Generated by packages/testing/element-collections.mjs.',
    files: Object.fromEntries(Object.entries(tree).sort(([left], [right]) => left.localeCompare(right))),
  }, null, 2)}\n`)
  return { total: Object.values(tree).reduce((sum, count) => sum + count, 0), files: Object.keys(tree).length }
}

if (path.resolve(process.argv[1] ?? '') === path.resolve(import.meta.dirname, 'element-collections.mjs')) {
  if (process.argv.includes('--check')) {
    const { total, files, problems } = checkElementCollections()
    for (const problem of problems) console.error(`element-collections: ${problem}`)
    if (problems.length > 0) process.exit(1)
    console.log(`element-collections: ${total} collections in ${files} files, as recorded`)
  } else {
    const { total, files } = writeElementCollections()
    console.log(`element-collections: recorded ${total} collections in ${files} files`)
  }
}
