// The logic and mechanism layers of the specs (D87): Vitest in browser mode,
// driving a local Chrome/Edge through Playwright, so the DOM, MutationObserver,
// ResizeObserver, layout and frames a spec reads are the browser's own.
// CHROME_PATH chooses the browser, as for the smoke. The behaviour layer drives
// the built page instead and has its own runner (packages/testing/behaviour.mjs).
//
// A spec reaches the product through three names only, which the aliases below
// resolve and lint holds (scripts/lint.mjs): the browser half's declared logic
// surface, the contract package and the engine's public modules.
//
// One module the source imports by name is generated by the build itself (D36).
// The specs get the same module, generated here into the run's own artifact
// directory from the same values (the motion tokens, D65); the names the build's
// module also carries need a bundle and are left out, so a spec reaching for one
// fails loudly instead of running against a stand-in.
import { defineConfig } from 'vitest/config'
import { playwright } from '@vitest/browser-playwright'
import fs from 'node:fs'
import path from 'node:path'
import { motionValues } from './scripts/shared/motion-tokens.mjs'
import { generatedSource } from './scripts/virtual-modules.mjs'
import { findChrome } from './packages/testing/browser.mjs'

const executablePath = findChrome()
if (executablePath === undefined) throw new Error('vitest: no Chrome or Edge found; set CHROME_PATH')

const SRC = path.resolve(import.meta.dirname, 'packages', 'client', 'src')
const GENERATED_FILE = path.resolve(import.meta.dirname, '.debug', 'vitest', 'generated.mjs')
const tokens = JSON.parse(fs.readFileSync(path.join(SRC, 'theme', 'tokens.json'), 'utf8'))
fs.mkdirSync(path.dirname(GENERATED_FILE), { recursive: true })
fs.writeFileSync(GENERATED_FILE, `${generatedSource({ MOTION: motionValues(tokens), PALETTE_CARDS: tokens.palette.cards })}\n`)

export default defineConfig({
  // The packages resolve the way the type check and the bundler resolve them,
  // from tsconfig.json's paths.
  resolve: {
    alias: {
      '@dsh-claude-style/client/pure': path.join(SRC, 'pure.ts'),
      '@dsh-claude-style/contracts': path.resolve(import.meta.dirname, 'packages/contracts/src'),
      '@dsh-claude-style/engine': path.resolve(import.meta.dirname, 'packages/engine/src'),
      'virtual:dsh-claude-style/generated': GENERATED_FILE,
    },
  },
  test: {
    include: ['packages/testing/specs/logic/**/*.spec.ts', 'packages/testing/specs/mechanism/**/*.spec.ts'],
    // The engine runs on a skin's vocabulary, which the specs hand over the way
    // the entry does (D73): their own, so no spec leans on the skin's names.
    setupFiles: ['packages/testing/specs/fixtures/setup.ts'],
    // Failure screenshots and other attachments are local artifacts.
    attachmentsDir: '.debug/vitest',
    // Browser mode binds a control port, and its own default (63315) falls inside
    // a Windows dynamic port exclusion on some machines: the bind fails with
    // EACCES before a single test runs. 51233 sits below the dynamic range's
    // start, outside every exclusion seen so far. Bind IPv4 explicitly so a
    // localhost lookup that prefers ::1 cannot miss it.
    api: { host: '127.0.0.1', port: 51233 },
    browser: {
      enabled: true,
      headless: true,
      provider: playwright({ launchOptions: { executablePath } }),
      instances: [{ browser: 'chromium' }],
    },
  },
})
