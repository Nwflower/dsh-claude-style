#!/usr/bin/env node
/**
 * dist-branch.mjs — commit the exact npm package to orphan `dist` and move its version
 * tag (D47); the scratch index leaves the checkout untouched.
 */
import fs from 'node:fs'
import path from 'node:path'
import { runner } from '../shared/run.mjs'
import { runsPath } from '../shared/debug-paths.mjs'

const ROOT = path.resolve(import.meta.dirname, '..', '..')
const DEBUG = runsPath(ROOT, 'dist')
const PACK = path.join(DEBUG, 'pack')
const TREE = path.join(DEBUG, 'tree')
const INDEX = path.join(DEBUG, 'index')

/** Every command starts in the repository; the git calls below run in the scratch tree. */
const run = runner(ROOT)

/** Run one git command against the scratch index and the packed tree. */
function git(args) {
  return run('git', args, {
    cwd: TREE,
    env: { ...process.env, GIT_DIR: path.join(ROOT, '.git'), GIT_WORK_TREE: TREE, GIT_INDEX_FILE: INDEX },
  })
}

const version = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).version
const tag = `v${version}`
fs.rmSync(DEBUG, { recursive: true, force: true })
fs.mkdirSync(PACK, { recursive: true })
fs.mkdirSync(TREE, { recursive: true })

// Build before packing because lib/ is absent from a fresh checkout (D47).
run('npm', ['run', 'build'])
const packed = run('npm', ['pack', '--pack-destination', PACK]).split('\n').pop()
run('tar', ['-xzf', path.join(PACK, packed), '-C', TREE, '--strip-components=1'])

// One release per version: a tag that already exists is the release commit this run is
// publishing, and it moves onto the dist commit below; a tag outside this history is
// another release, and the version must move.
const existing = run('git', ['tag', '--list', tag])
const ancestor = existing === '' ? true : (() => {
  try {
    // No `^{commit}` peel: this runs through a shell, and cmd.exe eats the caret.
    run('git', ['merge-base', '--is-ancestor', tag, 'HEAD'])
    return true
  } catch {
    return false
  }
})()
if (existing !== '' && !ancestor) throw new Error(`dist: ${tag} exists outside this history; bump the version before releasing`)

// One commit on an orphan branch: the branch carries the package, no history. The
// identity is this script's own: a CI runner has none configured and `commit-tree`
// refuses an empty one.
git(['read-tree', '--empty'])
git(['add', '--all'])
const tree = git(['write-tree'])
const commit = git([
  '-c', 'user.name=dsh-claude-style release',
  '-c', 'user.email=release@invalid',
  'commit-tree', tree, '-m',
  `chore(release): ${tag}\n\nGenerated by scripts/release/dist-branch.mjs from the ${tag} sources; the files are the npm package's own contents.`,
])
git(['update-ref', 'refs/heads/dist', commit])
// The tag follows the artifact: a tag install must get the same files npm got.
git(['tag', '--force', tag, commit])
console.log(`dist: tag ${tag} now points at ${commit.slice(0, 8)} (the packaged commit, not the release commit)`)
const files = git(['ls-tree', '--name-only', 'refs/heads/dist']).split('\n')
console.log(`dist: ${files.length} entries at ${commit.slice(0, 8)} (${tag})`)
for (const file of files) console.log(`  ${file}`)

if (process.argv.includes('--push')) {
  run('git', ['push', '--force', 'origin', 'refs/heads/dist:refs/heads/dist'])
  // The tag moved onto the packaged commit, so the push replaces it.
  run('git', ['push', '--force', 'origin', `refs/tags/${tag}`])
  console.log(`dist: pushed refs/heads/dist and ${tag}`)
} else {
  console.log('dist: branch and tag written locally; pass --push to send them')
}
